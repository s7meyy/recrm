// أحياء أضافها المستخدم يدويًا (تُحفَظ في المتصفح).
const CUSTOM_KEY = 'rabih:custom-districts';

const readCustom = () => {
  try { return JSON.parse(localStorage.getItem(CUSTOM_KEY) || '{}'); }
  catch { return {}; }
};

export function districtsOf(cityId) {
  const base = DISTRICTS[cityId] || [];
  const extra = readCustom()[cityId] || [];
  return [...new Set([...base, ...extra])].sort((a, b) => a.localeCompare(b, 'ar'));
}

export function addDistrict(cityId, name) {
  const clean = String(name || '').trim();
  if (!clean) return false;
  const custom = readCustom();
  const list = custom[cityId] || [];
  if (list.includes(clean) || (DISTRICTS[cityId] || []).includes(clean)) return false;
  custom[cityId] = [...list, clean];
  try { localStorage.setItem(CUSTOM_KEY, JSON.stringify(custom)); } catch { return false; }
  return true;
}
