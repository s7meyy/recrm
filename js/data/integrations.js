const ENDPOINT = '/api/integrations';

/** حالة السبعة من الخادم — أو `[]` إن تعذّر (بلا بوابة، أو دور مساعد). */
export async function loadIntegrations() {
  const res = await readPublicApi(ENDPOINT, { integrations: [] });
  const rows = res?.integrations || [];
  return rows.map((row) => ({ ...row, guide: INTEGRATION_GUIDE[row.key] || null }));
}

/**
 * ينفّذ إجراءً. **ولا يرمي عند «لم يُهيَّأ»**: تلك حالةٌ متوقَّعة تُعرض، لا عطبٌ يُلتقط.
 * @returns {{ ok, status?, missing?, error? }}
 */
export async function runIntegration(integration, action, payload = {}) {
  try {
    const res = await fetch(ENDPOINT, {
      method: 'POST',
      credentials: 'same-origin',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({ integration, action, payload }),
    });
    const body = await res.json().catch(() => ({}));
    if (res.ok) return { ok: true, ...body };
    return { ok: false, status: body.status || String(res.status), missing: body.missing || [], error: body.error || '' };
  } catch (err) {
    return { ok: false, status: 'offline', error: err.message };
  }
}

/** رسالةٌ تقول ما ينقص بالضبط — لا «تعذّر التنفيذ». */
export function explain(result, key) {
  const guide = INTEGRATION_GUIDE[key];
  if (result?.status === 'not_configured') {
    return `${guide?.label || key} غير مُهيَّأ بعد. الناقص: ${(result.missing || []).join('، ')} — افتح «التكاملات» لترى الخطوات.`;
  }
  if (result?.status === 'offline') return 'لا اتصال بالخادم الآن.';
  if (result?.status === 'provider_error') return `المزوّد ردّ بخطأ: ${result.error}`;
  if (result?.error) return result.error;
  // «تعذّر التنفيذ» وحدها لا تدلّ على فعل — وهي عين ما عبناه على الرسائل الغامضة.
  // فإن لم يصلنا سبب، فلنقل على الأقل **ما الذي ردّ به الخادم**.
  const code = result?.status && result.status !== 'false' ? ` (${result.status})` : '';
  return `تعذّر تنفيذ ${guide?.label || key}${code} — افتح «التكاملات» لترى حالته.`;
}
