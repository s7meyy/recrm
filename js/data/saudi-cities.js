/** أسماء المدن المعبّأة مسبقًا — الرياض أوّلها. */
export const BUILTIN_CITIES = [DEFAULT_CITY, ...Object.keys(CITIES)];

/**
 * أحياء مدينةٍ معبّأة مسبقًا، أو `[]` لمدينةٍ أضافها المستخدم بنفسه.
 * والفرز عربيّ كي تظهر القائمة مرتَّبةً كما يقرؤها صاحبها.
 */
export function builtinDistricts(city) {
  const name = String(city || '').trim();
  if (name === DEFAULT_CITY) return RIYADH_DISTRICTS;
  const list = CITIES[name];
  if (!list) return [];
  return [...new Set(list.map(clean).filter(Boolean))].sort((a, b) => a.localeCompare(b, 'ar'));
}

/**
 * مسودّة نطاقات الأحياء لمدينة.
 * الرياض بقطاعاتها الأربعة، وغيرها **نطاقٌ واحد** يشمل أحياءها — فتقسمه أنت بمعرفتك.
 */
export function builtinZones(city) {
  const name = String(city || '').trim();
  if (name === DEFAULT_CITY) {
    return RIYADH_SECTORS.map((s) => ({ key: s.key, label: s.label, districts: [...s.districts] }));
  }
  const districts = builtinDistricts(name);
  if (!districts.length) return [];
  return [{ key: 'all', label: `أحياء ${name}`, districts }];
}
