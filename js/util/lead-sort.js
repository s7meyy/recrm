/** أدنى فارقٍ يُحسم به الحكم — وما دونه التباسٌ يُقال. */
export const MIN_EDGE = 3;

function score(text, signs) {
  let total = 0;
  const why = [];
  for (const s of signs) {
    if (s.re.test(text)) { total += s.w; why.push(s.why); }
  }
  return { total, why };
}

/**
 * **الحكم على رسالةٍ واحدة.**
 *
 * @param {string} text نصُّ الرسالة كما وصل
 * @returns {{ kind: string, edge: number, want: number, offer: number, why: string[], scores: Record<string, number> }}
 *
 * `kind` هو `'unsure'` حين يتقارب أعلى صنفين أو حين لا شاهدَ أصلًا — **ولا يُرجَّح بلا دليل**.
 * و`edge` فارقُ الأوّل عن الثاني (لا يكون سالبًا)، و`want`/`offer` مجموعا الطلب والعرض
 * يبقيان كما كانا فلا ينكسر ما بُني عليهما.
 */
export function sortIncoming(text) {
  const t = prep(text);
  const zero = Object.fromEntries(KINDS.map((k) => [k.key, 0]));
  const empty = { kind: 'unsure', edge: 0, want: 0, offer: 0, why: [], scores: zero };
  if (!t) return empty;

  const graded = KINDS.map((k) => ({ ...k, ...score(t, k.signs) }));
  const scores = Object.fromEntries(graded.map((g) => [g.key, g.total]));
  const want = scores.request;
  const offer = scores.offer;

  // **ولا حكمَ بلا شاهد**: نصٌّ لا يحمل شيئًا من الأصناف ملتبسٌ لا «طلبٌ افتراضًا».
  const ranked = [...graded].sort((a, b) => b.total - a.total);
  if (!ranked[0].total) return { ...empty, want, offer, scores };

  const [top, second] = ranked;
  const edge = top.total - (second?.total || 0);
  if (edge >= MIN_EDGE) return { kind: top.key, edge, want, offer, why: top.why, scores };

  // متقاربان: يُعرض شاهدا الأوّلين معًا كي ترى أنت على أيّ شيءٍ تردّدَ.
  return { kind: 'unsure', edge, want, offer, why: [...top.why, ...(second?.why || [])], scores };
}

/** عنوانُ الحكم بالعربيّة — يُعرض وسمًا على البطاقة. */
export const KIND_LABELS = {
  ...Object.fromEntries(KINDS.map((k) => [k.key, k.label])),
  unsure: 'غير مؤكَّد',
};

/** الصيغةُ المنصوبة — تُقال في الحجّة وفي أزرار الاعتماد. */
export const KIND_ACC = Object.fromEntries(KINDS.map((k) => [k.key, k.acc]));

/**
 * جملةٌ تشرح الحكم — **فالفارزُ يُبيّن حجّته ولا يُملي**.
 * ومن رأى «حُكم طلبًا لأنّ فيه: فعل بحثٍ صريح · سقف ميزانيّة» صدّقه أو ردّه بعلم.
 */
export function sortReason(verdict) {
  if (!verdict || !verdict.why?.length) return 'لا شاهدَ في النصّ — الحكمُ لك.';
  const head = verdict.kind === 'unsure'
    ? 'شواهدُ أكثرَ من صنفٍ متقاربة'
    : `حُكم ${KIND_ACC[verdict.kind] || KIND_LABELS[verdict.kind]} لأنّ فيه`;
  // تُزال المكرّرات: شاهدان من قاعدةٍ واحدةٍ لا يُقالان مرّتين.
  return `${head}: ${[...new Set(verdict.why)].join(' · ')}.`;
}

/**
 * **بصمةُ الرسالة** — لكيلا يتضاعف الوارد.
 *
 * تيليجرام يعيد إرسال التحديث حتى نؤكّده، وأنت قد تحوّل الرسالةَ نفسها مرّتين وأنت
 * تظنّ الأولى لم تصل. **والنصُّ وحده هو البصمة**: هو ما يُقرأ منه الطلب، فتكرارُه
 * تكرارٌ ولو اختلف وقتُه.
 */
export function fingerprintText(text) {
  const t = prep(text).toLowerCase().replace(/[^\p{L}\p{N}]+/gu, '');
  let h = 5381;
  for (let i = 0; i < t.length; i++) h = ((h * 33) ^ t.charCodeAt(i)) >>> 0;
  return `${t.length.toString(36)}-${h.toString(36)}`;
}
