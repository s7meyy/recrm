/**
 * **ما هذه الرسالة؟** (المرحلة ٥١، ووُسِّعت في المرحلة ٥٣).
 *
 * تصلك في اليوم عشراتُ الرسائل في الواتساب، ونصفُها طالبٌ يبحث ونصفُها مالكٌ يعرض.
 * وفرزُها بيدك هو العملُ الممِلُّ الذي يُؤجَّل إلى المساء **ثم يُنسى**.
 *
 * وهذا الفارزُ **قواعدُ لا فهم**: يقرأ ما في النصّ من شواهدَ ويزنها. وهو مجّانيٌّ تمامًا،
 * يعمل بلا شبكةٍ ولا مفتاح، **ولا تخرج رسائلُ عملائك إلى أيّ مزوّد**.
 *
 * **وكان حكمين فصار ستّة** (المرحلة ٥٣): طلبٌ وعرضٌ — وهما ما يدخل مخزونك — ومعهما
 * **فرصةٌ عقاريّة** (بابٌ لم يُفتح بعد: مزادٌ أو ورثةٌ أو مالكٌ ينوي ولم يعرض)، و**مهمّةٌ**
 * (أمرٌ موجَّهٌ إليك بموعد)، و**مقترحٌ** (رأيٌ في البرنامج أو في طريقة العمل)، و**فكرةٌ**
 * (خاطرةٌ تُقيَّد لئلّا تضيع). **والسابعُ التباسٌ يُوسَم ولا يُخمَّن**: رسالةٌ تقول
 * «فلة حطين ٣ مليون» لا يُعرف أصاحبُها يعرضها أم يطلبها — والحكمُ فيها لك،
 * **وادّعاءُ يقينٍ كاذبٍ أسوأُ من الاعتراف بالجهل**.
 *
 * دوالُّ خالصة: لا تخزين ولا شبكة ولا DOM.
 */

/* تطبيعٌ يُبقي الأرقامَ والترقيم: الشواهدُ كلماتٌ، والأرقامُ تُعدّ شاهدًا بنفسها. */
const TASHKEEL = /[ؐ-ًؚ-ٰٟۖ-ۭ]/g;
const INVISIBLE = /[­؜​-‏‪-‮⁦-⁩﻿]/g;

function prep(value) {
  return String(value ?? '')
    .replace(INVISIBLE, '')
    .replace(TASHKEEL, '')
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ؤ/g, 'و')
    .replace(/ئ/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * **وحدودُ الكلمات لا تُكتب `\b`** — فهي في جافاسكربت حدودٌ بين محرفٍ لاتينيٍّ وغيره،
 * والعربيّةُ كلُّها «غيرُ ذلك» عندها، فـ`\bابحث\b` **لا تطابق شيئًا أبدًا**. فتُبنى
 * الحدودُ بنظرةٍ خلفيّةٍ وأماميّةٍ على صنف الحروف مع الراية `u` — وهي تفهم العربيّة.
 */
function word(...alts) {
  return new RegExp(`(?<!\\p{L})(?:${alts.join('|')})(?!\\p{L})`, 'u');
}

/**
 * **والشواهدُ تُكتب مطبَّعةً كما يُطبِّع `prep`** — وإلّا كانت حرفًا ميتًا لا يطابق شيئًا.
 *
 * فـ«لا تنسى» تصير في النصّ «لا تنسي»، و«أتمنى» تصير «اتمني»، و«عائد» تصير «عايد»،
 * و«مؤثثة» تصير «موثثه». **وهذا عطبٌ كشفه الاختبار في ثلاثةٍ من شواهد المرحلة ٥٣ قبل
 * أن يصيبك**، ووجد معها اثنين قديمين («نبغى» و«مؤثثة») لم يكن لهما بديلٌ حيٌّ أصلًا.
 * فلا تُكتب هنا همزةٌ ولا تاءٌ مربوطةٌ ولا ألفٌ مقصورة.
 */

