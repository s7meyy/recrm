/**
 * **أطلبٌ هذا أم عرض؟** (المرحلة ٥١).
 *
 * تصلك في اليوم عشراتُ الرسائل في الواتساب، ونصفُها طالبٌ يبحث ونصفُها مالكٌ يعرض.
 * وفرزُها بيدك هو العملُ الممِلُّ الذي يُؤجَّل إلى المساء **ثم يُنسى**.
 *
 * وهذا الفارزُ **قواعدُ لا فهم**: يقرأ ما في النصّ من شواهدَ ويزنها. وهو مجّانيٌّ تمامًا،
 * يعمل بلا شبكةٍ ولا مفتاح، **ولا تخرج رسائلُ عملائك إلى أيّ مزوّد**.
 *
 * **وثلاثةُ أحكامٍ لا حكمان**: طلبٌ، وعرضٌ، و**ملتبِسٌ يُوسَم ولا يُخمَّن**. فرسالةٌ
 * تقول «فلة حطين ٣ مليون» لا يُعرف أصاحبُها يعرضها أم يطلبها — والحكمُ فيها لك،
 * **وادّعاءُ يقينٍ كاذبٍ أسوأُ من الاعتراف بالجهل**.
 *
 * دوالُّ خالصة: لا تخزين ولا شبكة ولا DOM.
 */

/* تطبيعٌ يُبقي الأرقامَ والترقيم: الشواهدُ كلماتٌ، والأرقامُ تُعدّ شاهدًا بنفسها. */
const TASHKEEL = /[ؐ-ًؚ-ٰٟۖ-ۭ]/g;
const INVISIBLE = /[­؜​-‏‪-‮⁦-⁩﻿]/g;

function prep(value) {
  return String(value ?? '')
    .replace(INVISIBLE, '')
    .replace(TASHKEEL, '')
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ؤ/g, 'و')
    .replace(/ئ/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * **وحدودُ الكلمات لا تُكتب `\b`** — فهي في جافاسكربت حدودٌ بين محرفٍ لاتينيٍّ وغيره،
 * والعربيّةُ كلُّها «غيرُ ذلك» عندها، فـ`\bابحث\b` **لا تطابق شيئًا أبدًا**. فتُبنى
 * الحدودُ بنظرةٍ خلفيّةٍ وأماميّةٍ على صنف الحروف مع الراية `u` — وهي تفهم العربيّة.
 */
function word(...alts) {
  return new RegExp(`(?<!\\p{L})(?:${alts.join('|')})(?!\\p{L})`, 'u');
}

/**
 * **شواهدُ الطلب**: فعلُ بحثٍ أو رغبةٍ أو سؤال. ومن يطلب يتكلّم عن نفسه لا عن عقار.
 *
 * والوزنُ بقوّة الدلالة لا بطولها: «أبحث عن» لا تحتمل غيرَ الطلب، و«مطلوب» تحتملها
 * إعلاناتُ الوسطاء أحيانًا فوزنُها أقلّ.
 */
export const WANT_SIGNS = [
  { re: word('ابحث عن', 'ادور على', 'ادور علي', 'انا ابحث'), w: 5, why: 'فعلُ بحثٍ صريح' },
  { re: word('ابي', 'ابغى', 'ابغي', 'اريد', 'ودي', 'نبي', 'نبغى'), w: 4, why: 'فعلُ رغبةٍ عامّيّ' },
  { re: word('مطلوب'), w: 3, why: '«مطلوب»' },
  { re: word('عندك', 'عندكم', 'يوجد لديكم', 'فيه عندك', 'توفر لديكم', 'متوفر عندكم'), w: 4, why: 'سؤالٌ عن توفّره عندك' },
  { re: word('ميزانيتي', 'ميزانيه', 'حدود', 'في حدود', 'لا يتجاوز', 'ما يزيد عن', 'بحدود'), w: 3, why: 'سقفُ ميزانيّة' },
  { re: word('للشراء', 'للايجار', 'اشتري', 'استاجر', 'نشتري', 'نستاجر'), w: 3, why: 'فعلُ شراءٍ أو استئجار' },
  { re: word('محتاج', 'احتاج', 'نحتاج'), w: 3, why: 'فعلُ حاجة' },
];

/**
 * **شواهدُ العرض**: إعلانٌ عن عقارٍ بعينه. ومن يعرض يتكلّم عن العقار لا عن نفسه،
 * **ويذكر ما لا يذكره الطالب**: الصكَّ والواجهةَ وعرضَ الشارع ورقمَ الترخيص.
 */
export const OFFER_SIGNS = [
  { re: word('للبيع', 'للايجار المباشر', 'معروض', 'للتقبيل'), w: 5, why: '«للبيع» أو «معروض»' },
  { re: word('فرصه', 'فرصة', 'فرصه استثماريه', 'تخفيض', 'بسعر مغري'), w: 3, why: 'لغةُ إعلان' },
  { re: word('الصك', 'صك الكتروني', 'صك إلكتروني', 'حجه', 'حجة'), w: 4, why: 'ذكرُ الصكّ' },
  { re: word('واجهه', 'واجهة', 'واجهتين', 'شارع عرض', 'عرض الشارع', 'شارعين', 'زاويه', 'زاوية'), w: 4, why: 'وصفُ الأطوال والشوارع' },
  { re: word('رقم الترخيص', 'ترخيص الاعلان', 'فال', 'رخصه اعلان'), w: 5, why: 'رقمُ ترخيص إعلان' },
  { re: word('السوم', 'سوم', 'المزايده', 'المزايدة', 'قابل للتفاوض'), w: 3, why: 'لغةُ مساومة' },
  { re: word('الموقع', 'الاحداثيات', 'على الخارطه', 'خرائط جوجل'), w: 2, why: 'موقعٌ مرفق' },
  { re: word('مساحه الارض', 'مساحة الأرض', 'عمر البناء', 'تشطيب', 'مؤثثه', 'مؤثثة', 'دور ارضي', 'دورين'), w: 3, why: 'وصفُ مبنًى قائم' },
];

/** أدنى فارقٍ يُحسم به الحكم — وما دونه التباسٌ يُقال. */
export const MIN_EDGE = 3;

function score(text, signs) {
  let total = 0;
  const why = [];
  for (const s of signs) {
    if (s.re.test(text)) { total += s.w; why.push(s.why); }
  }
  return { total, why };
}

/**
 * **الحكم على رسالةٍ واحدة.**
 *
 * @param {string} text نصُّ الرسالة كما وصل
 * @returns {{ kind: 'request'|'offer'|'unsure', edge: number, want: number, offer: number, why: string[] }}
 *
 * `kind` هو `'unsure'` حين يتقارب الوزنان أو حين لا شاهدَ أصلًا — **ولا يُرجَّح بلا دليل**.
 */
export function sortIncoming(text) {
  const t = prep(text);
  const empty = { kind: 'unsure', edge: 0, want: 0, offer: 0, why: [] };
  if (!t) return empty;

  const want = score(t, WANT_SIGNS);
  const offer = score(t, OFFER_SIGNS);
  const edge = want.total - offer.total;

  // **ولا حكمَ بلا شاهد**: نصٌّ لا يحمل شيئًا من الطرفين ملتبسٌ لا «طلبٌ افتراضًا».
  if (!want.total && !offer.total) return empty;

  if (edge >= MIN_EDGE) {
    return { kind: 'request', edge, want: want.total, offer: offer.total, why: want.why };
  }
  if (-edge >= MIN_EDGE) {
    return { kind: 'offer', edge, want: want.total, offer: offer.total, why: offer.why };
  }
  // متقاربان: يُعرض الشاهدان معًا كي ترى أنت على أيّ شيءٍ تردّدَ.
  return { kind: 'unsure', edge, want: want.total, offer: offer.total, why: [...want.why, ...offer.why] };
}

/** عنوانُ الحكم بالعربيّة — يُعرض وسمًا على البطاقة. */
export const KIND_LABELS = { request: 'طلب', offer: 'عرض', unsure: 'غير مؤكَّد' };

/**
 * جملةٌ تشرح الحكم — **فالفارزُ يُبيّن حجّته ولا يُملي**.
 * ومن رأى «حُكم طلبًا لأنّ فيه: فعل بحثٍ صريح · سقف ميزانيّة» صدّقه أو ردّه بعلم.
 */
export function sortReason(verdict) {
  if (!verdict || !verdict.why?.length) return 'لا شاهدَ في النصّ — الحكمُ لك.';
  const head = verdict.kind === 'unsure'
    ? 'شواهدُ الطرفين متقاربة'
    : `حُكم ${KIND_LABELS[verdict.kind]}ًا لأنّ فيه`;
  // تُزال المكرّرات: شاهدان من قاعدةٍ واحدةٍ لا يُقالان مرّتين.
  return `${head}: ${[...new Set(verdict.why)].join(' · ')}.`;
}

/**
 * **بصمةُ الرسالة** — لكيلا يتضاعف الوارد.
 *
 * تيليجرام يعيد إرسال التحديث حتى نؤكّده، وأنت قد تحوّل الرسالةَ نفسها مرّتين وأنت
 * تظنّ الأولى لم تصل. **والنصُّ وحده هو البصمة**: هو ما يُقرأ منه الطلب، فتكرارُه
 * تكرارٌ ولو اختلف وقتُه.
 */
export function fingerprintText(text) {
  const t = prep(text).toLowerCase().replace(/[^\p{L}\p{N}]+/gu, '');
  let h = 5381;
  for (let i = 0; i < t.length; i++) h = ((h * 33) ^ t.charCodeAt(i)) >>> 0;
  return `${t.length.toString(36)}-${h.toString(36)}`;
}
