//
// قيسَ فعلًا لا ظنًّا. على خمسة آلاف عقار: صفحة العقارات تستغرق **٣٫٦ ثانية** وتضع في
// الصفحة **٩٥٬٣٥٣ عنصرًا**، وصفحة العملاء على ألفين: ٢٫٢ ثانية و٢٨٬١٩٤ عنصرًا. وذلك على
// حاسوب؛ وعلى جوّالٍ في السيارة أسوأ. أما «يومي» و«الداشبورد» فتحت ربع ثانية لأنهما
// تُجمِّعان ولا تسردان — فالعلّة في **السرد** لا في البيانات.
//
// **والفرز والبحث والعدّ تبقى على المجموعة كاملة**، فلا يكذب رقمٌ ولا يختفي مطابقٌ من
// نتيجة بحث. المحدود هو ما يُرسم في الصفحة وحده — وهو ما لا تراه العين أصلًا.

/** كم عنصرًا يُرسم قبل الزرّ. مئتان تملأ عدّة شاشات، وتبقي الصفحة تحت نصف ثانية. */
export const PAGE_SIZE = 200;

/**
 * يقصّ القائمة ويعيد معها زرّ «أظهر المزيد».
 *
 * @param {Array} items القائمة كاملة (بعد الفرز والبحث)
 * @param {number} shown كم عنصرًا يُعرض الآن
 * @param {(next: number) => void} onMore تُستدعى بالعدد الجديد
 * @param {(n: number) => Node} makeButton باني الزرّ (كي لا يعتمد هذا الملف على DOM المشروع)
 * @returns {{ visible: Array, more: number }}
 */
export function capped(items = [], shown = PAGE_SIZE) {
  const limit = Math.max(1, shown);
  return { visible: items.slice(0, limit), more: Math.max(0, items.length - limit) };
}
