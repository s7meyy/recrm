// ما يخرج من العرض إلى الناس (المرحلة ٤٨).
//
// كان الخارجُ إلى الصفحة العامّة: النوعَ والمدينةَ والحيَّ والمساحةَ والسعرَ والملاحظاتِ
// والصورَ والموقع. **و`typeFields` لا يخرج** — وفيه الغرفُ ودوراتُ المياه والدورُ وعمرُ
// البناء والواجهاتُ وعرضُ الشارع، وهي الحقولُ التي بُنيت لكلّ نوعٍ بعينه.
//
// فأوّلُ سؤالٍ يسأله المشتري — «كم غرفة؟» — لا جواب له إلّا أن يُكتب بيدك في الملاحظات،
// فيصير الحقلُ مكتوبًا مرّتين: مرّةً في مكانه ومرّةً نصًّا حرًّا.

/**
 * **الحقولُ التي تُنشر** — قائمةٌ بيضاء لا «كلُّ ما في `typeFields`».
 *
 * و**رقمُ المخطط ورقمُ القطعة خارجها قصدًا**: هما معرّفان يُوصلان إلى الصك لا وصفٌ
 * يُرغِّب، ونشرُهما يُغني الزائرَ عنك. أمّا ما هنا فوصفٌ يُعين على القرار، وهو ما
 * يُسأل عنه في أوّل رسالة.
 */
export const PUBLIC_FACT_KEYS = [
  'rooms', 'baths', 'floor', 'floorsCount', 'buildingAge', 'buildingCondition',
  'plotDimensions', 'streetWidth', 'streetsCount', 'facades',
];

/**
 * حقائقُ العرض للنشر: `{ key: value }` بالمفاتيح لا بالعناوين.
 *
 * **والمفتاحُ لا العنوان** لأنّ الصفحة العامّة تُعرض بالعربية والإنجليزية، وعنوانٌ
 * عربيٌّ مُرسَلٌ جاهزًا يبقى عربيًّا في الإنجليزية. وما لم يُملأ لا يخرج أصلًا — فلا
 * يُطبع «الغرف: —» على إعلانٍ يُقرأ.
 */
export function publicFacts(property) {
  const src = property?.typeFields || {};
  const out = {};
  for (const key of PUBLIC_FACT_KEYS) {
    const v = src[key];
    if (v == null || v === '' || (typeof v === 'string' && !v.trim())) continue;
    out[key] = typeof v === 'string' ? v.trim() : v;
  }
  return out;
}

/**
 * **كم له معروضًا** — بالأشهر، أو `null` إن لم يُعرف.
 *
 * الصفحةُ كانت تعرض تاريخًا واحدًا: متى نُشرت اللقطةُ كلُّها. فالعرضُ المضاف اليوم
 * والعرضُ القائم منذ سنةٍ يظهران بالتاريخ نفسِه — وهو تاريخُ آخر ضغطةٍ على «انشر»،
 * لا عمرُ العرض.
 *
 * **وهذا في صالحك لا ضدَّك**: الطازجُ يُقرأ طازجًا بدل أن يُخلط بغيره، والقديمُ يُعرف
 * فيُفاوَض عليه بدل أن يُتجاهَل.
 */
export function listedMonths(iso, now = Date.now()) {
  const t = new Date(iso || '').getTime();
  if (!Number.isFinite(t) || t > now) return null;
  return Math.floor((now - t) / (30 * 86400000));
}
