/** يبني كتلة البيانات التي تُرفَق بالرسائل. */
export function buildDataBlock(place, ctx = {}) {
  const s = stats(place);
  const id = place.identity;
  const lines = [];

  lines.push('## بطاقة المنشأة');
  lines.push(`- الاسم: ${id.name || 'غير متوفّر'}`);
  lines.push(`- النشاط كما في قوقل: ${id.category || 'غير متوفّر'}`);
  if (ctx.categoryName) lines.push(`- التصنيف المعتمد في التقرير: ${ctx.categoryName}`);
  lines.push(`- المدينة: ${ctx.cityName || 'غير متوفّر'}`);
  lines.push(`- الحي: ${ctx.districtName || 'غير متوفّر'}`);
  lines.push(`- العنوان: ${id.address || 'غير متوفّر'}`);
  if (id.phone) lines.push(`- الهاتف: ${id.phone}`);
  if (id.website) lines.push(`- الموقع: ${id.website}`);
  if (id.priceLevel) lines.push(`- مستوى الأسعار: ${id.priceLevel}`);
  if (id.hours?.length) lines.push(`- ساعات العمل:\n${id.hours.map((h) => `  - ${h}`).join('\n')}`);
  if (id.attributes?.length) lines.push(`- المميزات المعلنة: ${id.attributes.join('، ')}`);
  if (place.mapsUrl) lines.push(`- رابط قوقل مابز: ${place.mapsUrl}`);

  lines.push('\n## الإحصاءات المحسوبة (نهائية — لا تُعاد حسابها)');
  lines.push(`- متوسط التقييم في قوقل: ${s.googleAverage ?? 'غير متوفّر'}`);
  lines.push(`- إجمالي التقييمات في قوقل: ${s.googleCount ?? 'غير متوفّر'}`);
  lines.push(`- عدد التعليقات المتاحة للتحليل: ${s.total}`);
  if (s.coverage !== null) lines.push(`- نسبة العيّنة من إجمالي التقييمات: ${s.coverage}%`);
  lines.push(`- متوسط نجوم العيّنة: ${s.sampleAverage ?? 'غير متوفّر'}`);
  if (s.distribution) {
    lines.push(`- توزيع النجوم في العيّنة: 5★=${s.distribution[5]} · 4★=${s.distribution[4]} · 3★=${s.distribution[3]} · 2★=${s.distribution[2]} · 1★=${s.distribution[1]}`);
  }
  lines.push(`- إيجابي (4–5): ${s.positive} · محايد (3): ${s.neutral} · سلبي (1–2): ${s.negative}`);
  lines.push(`- نسبة ردّ المالك على التعليقات: ${s.replyRate !== null ? s.replyRate + '%' : 'غير متوفّر'} (${s.withReply} من ${s.total})`);

  // إحصاء المواضيع محسوب برمجيًّا من نصوص التعليقات، فلا يقدّره النموذج ولا يعيد عدّه.
  const topics = topicStats(place);
  if (topics.length) {
    lines.push('\n## المواضيع المرصودة آليًّا (نهائية — لا تُعاد عدّتها)');
    lines.push('| الموضوع | مرات الورود | إيجابي | سلبي | الاتجاه | المعرّفات |');
    lines.push('|---|---|---|---|---|---|');
    for (const t of topics) {
      lines.push(`| ${t.name} | ${t.total} | ${t.pos} | ${t.neg} | ${t.verdict} | ${t.ids.join('، ')} |`);
    }
    const miss = uncovered(place);
    if (miss.length) lines.push(`\nتعليقات لم يصنّفها القاموس، اقرأها بنفسك ولا تُهملها: ${miss.join('، ')}`);
  }

  // الحداثة: متوسطٌ عامٌّ قد يخفي انحدارًا حديثًا، فيُسلَّم الفرق محسوبًا.
  const rec = recentVsOlder(place);
  if (rec.recent.n || rec.older.n) {
    lines.push('\n## القراءة الزمنية (نهائية — محسوبة من تواريخ التعليقات)');
    lines.push(`- آخر ${rec.window} يومًا: ${rec.recent.n} تعليقًا، متوسط ${rec.recent.avg ?? 'غير متوفّر'}${rec.recent.neg !== null ? `، نسبة السلبي ${rec.recent.neg}%` : ''}`);
    lines.push(`- ما قبلها: ${rec.older.n} تعليقًا، متوسط ${rec.older.avg ?? 'غير متوفّر'}${rec.older.neg !== null ? `، نسبة السلبي ${rec.older.neg}%` : ''}`);
    lines.push(`- الحكم: ${rec.verdict}${rec.diff !== null ? ` (فرق ${rec.diff})` : ''}`);
    if (rec.undated) lines.push(`- ${rec.undated} تعليقًا بلا تاريخ مفهوم، فلم يدخل هذه القراءة.`);

    const months = monthly(place);
    if (months.length >= 3) {
      lines.push('\n| الفترة | عدد التعليقات | المتوسط | السلبي |');
      lines.push('|---|---|---|---|');
      for (const m of months) lines.push(`| ${m.label} | ${m.n} | ${m.avg ?? '—'} | ${m.neg} |`);
    }

    const ages = topicAges(place).filter((t) => t.state !== 'قديمة');
    if (ages.length) {
      lines.push('\n### حال الشكاوى اليوم');
      for (const t of ages) lines.push(`- ${t.name}: ${t.state} — ${t.recentNeg} حديثة، ${t.olderNeg} قديمة`);
    }
  }

  const ent = entitiesBlock(place);
  if (ent) lines.push(ent);

  const rep = repliesBlock(place);
  if (rep) lines.push(rep);

  const ctxBlock = contextBlock(place);
  if (ctxBlock) lines.push(ctxBlock);

  const warn = alerts(place);
  if (warn.length) {
    lines.push('\n## إنذارات زمنية مرصودة آليًّا (اذكرها في التقرير ولا تتجاهلها)');
    warn.forEach((a) => lines.push(`- ${a}`));
  }

  if (place.qna?.length) {
    lines.push('\n## أسئلة وأجوبة');
    place.qna.forEach((q, i) => lines.push(`- س${i + 1}: ${q.question}\n  ج: ${q.answer || 'بلا إجابة'}`));
  }
  if (place.notes?.trim()) {
    lines.push('\n## ملاحظات أضافها صاحب التقرير (بيانات موثوقة)');
    lines.push(place.notes.trim());
  }

  lines.push('\n## التعليقات (المصدر الوحيد للاستنتاج)');
  for (const r of place.reviews) {
    const head = [`[${r.id}]`, r.rating ? `${r.rating}★` : 'بلا تقييم', r.author || 'بلا اسم', r.date || 'بلا تاريخ'].join(' · ');
    lines.push(`\n${head}\n${(r.text || '(بلا نص)').trim()}`);
    if (r.ownerReply?.trim()) lines.push(`↩ رد المالك: ${r.ownerReply.trim()}`);
  }
  return lines.join('\n');
}

