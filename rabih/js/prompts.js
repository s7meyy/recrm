/**
 * حدُّ التعليقات في الدفعة الواحدة.
 *
 * نوافذ النماذج المجانية تضيق عن مئات التعليقات، والأسوأ أن التجاوز **صامت**:
 * النموذج يقتطع ما زاد ويجيبك إجابةً تبدو سليمة، وقد بُنيت على نصف بياناتك
 * وأنت لا تدري. فتُقسَّم الدفعات، ويُقال لك أنها قُسِّمت وكم دفعة.
 */
export const BATCH_REVIEWS = 60;

/** كم دفعةً يحتاج هذا العدد من التعليقات؟ */
export const batchCount = (n) => Math.max(1, Math.ceil(n / BATCH_REVIEWS));

/**
 * ترتيب التعليقات للتقسيم: **بالموضوع لا بترتيب ورودها**.
 *
 * الدفعة تُنظَّم وحدها، فإذا تفرّق كلام موضوعٍ واحد على دفعتين لم يرَ النموذج
 * الصورة كاملة في أيٍّ منهما، فيقول «ورد مرة» عمّا تكرّر خمسًا. فتُجمَع
 * تعليقات الموضوع الواحد معًا ما أمكن.
 *
 * **ولا يسقط تعليق ولا يتكرّر**: كل تعليق يُوضَع في موضوعه الأول فقط، وما لا
 * موضوع له يُلحَق في الآخر. والمجموع مضمونٌ بفحصٍ دائم في الاختبارات.
 */
export function orderedForBatches(place) {
  const reviews = place?.reviews || [];
  const placed = new Set();
  const buckets = new Map();

  for (const r of reviews) {
    const t = topicsOf(r.text || '')[0] || '';
    if (!buckets.has(t)) buckets.set(t, []);
    buckets.get(t).push(r);
    placed.add(r.id);
  }

  // الموضوع الأكثر ورودًا أولًا، وبلا موضوعٍ في الآخر.
  const groups = [...buckets.entries()]
    .sort((a, b) => (a[0] === '' ? 1 : b[0] === '' ? -1 : b[1].length - a[1].length));

  const out = groups.flatMap(([, list]) => list);
  // حارسٌ: إن اختلّ شيء رُدَّ الترتيب الأصلي، ولا يُخاطَر بإسقاط تعليق.
  return out.length === reviews.length ? out : reviews;
}

/** نسخةٌ من المنشأة بتعليقات دفعةٍ واحدة — والمعرّفات تبقى كما هي عالميًّا. */
export function sliceForBatch(place, index) {
  const ordered = orderedForBatches(place);
  const from = index * BATCH_REVIEWS;
  return { ...place, reviews: ordered.slice(from, from + BATCH_REVIEWS) };
}

/**
 * يفصل مخرجَ خطوةٍ مقسَّمة إلى دفعاتها، بالعلامة التي كُتبت بها.
 * وإن لم توجد العلامة (لصقٌ بيد المستخدم) قُسِّم بالتساوي تقريبًا على الفقرات.
 */
export function splitBatches(text, parts) {
  const s = String(text || '');
  if (parts <= 1) return [s];
  const marked = s.split(/\n---\n(?=## دفعة \d+ من \d+)/);
  if (marked.length === parts) return marked;

  // لا علامات: يُقسَّم على حدود الأسطر قسمةً متقاربة، ولا يُقطَع سطرٌ نصفين.
  const lines = s.split('\n');
  const per = Math.ceil(lines.length / parts);
  return Array.from({ length: parts }, (_, i) => lines.slice(i * per, (i + 1) * per).join('\n'));
}

/** رسالة التوحيد لدفعةٍ واحدة، مُصرَّحٌ فيها بموضعها من الكل. */
export function promptNormalizeBatch(place, ctx, index, total) {
  const part = sliceForBatch(place, index);
  const ids = part.reviews.length
    ? `${part.reviews[0].id} إلى ${part.reviews[part.reviews.length - 1].id}`
    : 'لا شيء';
  return promptNormalize(part, ctx).replace(
    '# مهمتك: تنظيم البيانات الخام لا تحليلها',
    `# مهمتك: تنظيم البيانات الخام لا تحليلها

> **هذه الدفعة ${index + 1} من ${total}** — تعليقاتها ${ids} من أصل ${place.reviews.length}.
> نظّم ما فيها وحدها، ولا تُشِر إلى تعليقٍ ليس فيها، ولا تستنتج عن المنشأة كلها.`,
  );
}

