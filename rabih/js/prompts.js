/** المرحلة 3 — الإخراج المصمَّم. */
export function promptDesign(finalReport, place, ctx) {
  return `${CHARTER}

# مهمتك: تحويل التقرير إلى صفحة HTML عربية مصمَّمة للطباعة
أعد صياغة **محتوى التقرير كما هو** داخل صفحة HTML واحدة كاملة، بلا حذف ولا إضافة معنى.

## متطلبات فنية مُلزِمة
- ملف HTML واحد مكتفٍ بذاته: \`<!doctype html>\` و\`<html dir="rtl" lang="ar">\`، وكل الـCSS داخل \`<style>\`.
- ممنوع أي ملف خارجي أو خط من الإنترنت أو صورة من رابط خارجي. الخطوط من النظام: \`font-family: "Segoe UI", Tahoma, sans-serif\`.
- مقاس الصفحة A4 مع \`@page { size: A4; margin: 18mm 15mm; }\`، وترقيم الصفحات في التذييل.
- \`@media print\` يمنع قطع العناوين والجداول عن محتواها (\`break-inside: avoid\`).
- صفحة غلاف: اسم المنشأة، التصنيف، المدينة والحي، متوسط التقييم وعدد التقييمات، تاريخ التقرير، وكلمة «رابح» كمصدر التقرير.
- فهرس محتويات مُرقَّم بعد الغلاف.
- الأقسام مرقَّمة ترقيمًا هرميًّا (1، 1-1، 1-2...).
- شريط توزيع النجوم مرسوم بـCSS خالص (\`div\` بعرض نسبي) لا بصورة ولا بمكتبة.
- لوحة ألوان هادئة احترافية: كحلي وذهبي ورمادي، والنص أسود على أبيض ليصلح للطباعة.
- مكان الصور: ضع \`<img src="__PHOTO_1__">\` و\`__PHOTO_2__\` و\`__PHOTO_3__\` داخل قسم «صور المنشأة»؛ المنصّة تستبدلها لاحقًا. لا تضع روابط صور حقيقية.

## ممنوعات
- لا تغيّر رقمًا ولا تحذف قسمًا ولا تلخّص فقرة من التقرير.
- لا تضف رأيًا ولا عبارة تسويقية ولا شعارًا ليس في التقرير.
- أخرج الشيفرة وحدها بلا شرح قبلها ولا بعدها.

## بيانات الغلاف
- المنشأة: ${place.identity.name || 'غير متوفّر'}
- التصنيف: ${ctx.categoryName || 'غير متوفّر'}
- المدينة والحي: ${ctx.cityName || 'غير متوفّر'}${ctx.districtName ? ' — ' + ctx.districtName : ''}
- متوسط التقييم: ${place.ratings?.average ?? 'غير متوفّر'} من 5
- عدد التقييمات: ${place.ratings?.count ?? 'غير متوفّر'}
- تاريخ التقرير: ${new Date().toLocaleDateString('ar-SA-u-ca-gregory')}

---
## التقرير المطلوب إخراجه
${finalReport || '(يُلصَق هنا التقرير الموحَّد النهائي)'}`;
}

/**
 * رسالة مسوّدات الردود — أقوى رافعة بيد المالك وأرخصها.
 *
 * والمنصّة ترصد «٠٪ ردّ على الشكاوى» ثم تسكت. فهذه تُخرج مسوّدةً لكل شكوى
 * بلا ردّ، **مقترحًا للمالك لا بيانات**: يقرؤها ويحرّرها ويرسلها بنفسه.
 *
 * وقواعدها تحمي صاحب المحل من نفسه: لا ينفي ما قاله العميل، ولا يَعِد بما
 * لم يقرّره، ولا يجادل علنًا. والاعتذار الذي لا يُتبَع بفعلٍ يُحفَظ ماء الوجه
 * ولا يُصلح شيئًا، فيُطلَب الفعل صراحةً.
 */
export function promptReplyDrafts(place, ctx = {}) {
  const unanswered = (place.reviews || [])
    .filter((r) => (r.rating !== null && r.rating <= 3) || /سيء|سيئ|زفت|مقرف|فاشل/.test(r.text || ''))
    .filter((r) => !(r.ownerReply || '').trim() && (r.text || '').trim())
    .slice(0, 15);

  const block = unanswered.length
    ? unanswered.map((r) => `### ${r.id}${r.rating ? ` — ${r.rating} من 5` : ' — بلا تقييم'}${r.date ? ` — ${r.date}` : ''}
${r.text}`).join('\n\n')
    : '(لا شكوى بلا ردّ — أحسنتَ.)';

  return `${CHARTER}

# مهمتك: مسوّدات ردود على الشكاوى التي لم يُرَدّ عليها
اكتب ردًّا مقترحًا لكل شكوى أدناه، ليراجعه صاحب المنشأة وينشره بنفسه.

## قواعد الردّ — مُلزِمة
- **لا تنفِ ما قاله العميل ولا تشكّك فيه**، ولو بدا مبالغًا. هو شهد بما رأى.
- **لا تَعِد بما لم يقرّره صاحب المنشأة**: لا تعويض ولا خصم ولا تغيير موظف. وإن لزم وعدٌ فاكتب بين قوسين معقوفين [يقرّره المالك].
- **لا تجادل ولا تشرح ظروف المنشأة**؛ الردّ العلني ليس موضع دفاع.
- اعترف بما ورد، واذكر **فعلًا محدَّدًا** إن أمكن استخلاصه من الشكوى نفسها، وادعُ إلى قناةٍ خاصة لإتمام المعالجة.
- **ثلاثة أسطر على الأكثر**، بعربية مهذَّبة قريبة لا رسمية جافّة، وبلا قوالب مكرّرة: لكل شكوى ردُّها.
- لا تقتبس كلام العميل حرفيًّا في الردّ العلني إن كان جارحًا؛ أشِر إلى المعنى.

## الصيغة
لكل شكوى: سطر \`### المعرّف\` ثم نصّ الردّ وحده، بلا شرح ولا تعليق.

## المنشأة
${place.identity?.name || 'غير متوفّر'}${ctx.categoryName ? ` — ${ctx.categoryName}` : ''}${ctx.cityName ? ` — ${ctx.cityName}` : ''}

## الشكاوى بلا ردّ
${block}`;
}

