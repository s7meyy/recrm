// اختبار وحدة (المرحلة ٤٦): فرقُ الفترة عن سابقتها.
//
// **الحدُّ المحروس:** لا «∞٪» ولا `NaN` ولا قسمةٌ على صفر — وهذه ثلاثةُ ما يكسر لوحةَ أرقام.
import { deltaOf } from '../js/util/format.js';

const ok = (n, c, x = '') => console.log(`${c ? 'PASS' : 'FAIL'} — ${n}${x ? ' :: ' + x : ''}`);

const up = deltaOf(150, 100);
ok('الصعود يُعرف ونسبته', up.kind === 'change' && up.up === true && up.pct === 50, JSON.stringify(up));
const down = deltaOf(50, 100);
ok('والنزول كذلك', down.kind === 'change' && down.up === false && down.pct === -50, JSON.stringify(down));
ok('والصعود خبرٌ سارّ افتراضًا', up.good === true && down.good === false);

/* المصاريف: النزول سارّ — فينقلب الحكم وحده */
ok('نزولُ المصاريف حكمُه سارّ', deltaOf(50, 100, { lowerIsBetter: true }).good === true);
ok('وصعودُها سيّئ', deltaOf(150, 100, { lowerIsBetter: true }).good === false);
ok('والسهم يتبع الرقم لا الحكم', deltaOf(50, 100, { lowerIsBetter: true }).up === false);

/* ===== ما لا يُحسب نسبةً ===== */
ok('التساوي لا فرقَ له', deltaOf(100, 100).kind === 'same');
ok('وسابقٌ بصفرٍ لا يُقسم عليه', deltaOf(100, 0).kind === 'noBase');
ok('والصفران معًا تساوٍ', deltaOf(0, 0).kind === 'same');
ok('والنزول إلى صفرٍ يُحسب نسبةً كاملة', deltaOf(0, 100).kind === 'change' && deltaOf(0, 100).pct === -100);

ok('ولا «∞» ولا `NaN` في أيّ حال',
  [[100, 0], [0, 0], [0, 100], [-50, 100], [100, -100], [5, -5]].every(([a, b]) => {
    const d = deltaOf(a, b);
    return Number.isFinite(d.pct) && !Number.isNaN(d.pct);
  }));

ok('والسالب يُقرأ ولا ينهار', deltaOf(-50, 100).up === false && Number.isFinite(deltaOf(-50, 100).pct));
ok('والأساس السالب يُقسم على قيمته المطلقة', deltaOf(-50, -100).pct === 50, JSON.stringify(deltaOf(-50, -100)));
ok('وغيرُ الأرقام يُعامَل صفرًا', deltaOf('كثير', 'قليل').kind === 'same');
ok('والنسبة تُقرّب صحيحةً', deltaOf(133, 100).pct === 33 && Number.isInteger(deltaOf(133, 100).pct));

/* ===== تفقيط المبلغ (المرحلة ٤٦) ===== */
import { amountInWords } from '../js/util/format.js';

const w = (n) => amountInWords(n);

/* الآحاد: التمييز يتبع العدد، والواحدُ والاثنان لا يُسبقان برقم */
ok('الواحد «ريال واحد» لا «واحد ريال»', w(1) === 'ريال واحد', w(1));
ok('والاثنان مثنًّى بلا رقم', w(2) === 'ريالان', w(2));
ok('والثلاثة جمعُ قلّة', w(3) === 'ثلاثة ريالات', w(3));
ok('والعشرة كذلك', w(10) === 'عشرة ريالات', w(10));
ok('والأحدَ عشرَ مفردٌ منصوب', w(11) === 'أحد عشر ريالًا', w(11));
ok('والآحادُ قبل العشرات', w(21) === 'واحد وعشرون ريالًا', w(21));

/* المئات: تمييزُها مفردٌ، والمائتان تسقط نونُها في الإضافة */
ok('المائة تُمَيَّز بمفرد', w(100) === 'مائة ريال', w(100));
ok('والمائتان «مائتا ريال» لا «مائتان ريال»', w(200) === 'مائتا ريال', w(200));
ok('والتمييز يتبع آخرَ العدد', w(325) === 'ثلاثمائة وخمسة وعشرون ريالًا', w(325));

/* الآلاف */
ok('الألف مفرد', w(1000) === 'ألف ريال', w(1000));
ok('والألفان تسقط نونُهما', w(2000) === 'ألفا ريال', w(2000));
ok('والثلاثة آلافٍ جمعُ قلّة', w(3000) === 'ثلاثة آلاف ريال', w(3000));
ok('والأحدَ عشرَ ألفًا يسقط تنوينُه أمام التمييز', w(11000) === 'أحد عشر ألف ريال', w(11000));
ok('والمئاتُ تُفصل عمّا دونها', w(525000) === 'خمسمائة ألف وخمسة وعشرون ألف ريال', w(525000));
ok('ومائتا ألف', w(200000) === 'مائتا ألف ريال', w(200000));
ok('ومائة ألف وألف', w(101000) === 'مائة ألف وألف ريال', w(101000));

/* الملايين */
ok('المليون مفرد', w(1000000) === 'مليون ريال', w(1000000));
ok('والمليونان تسقط نونُهما', w(2000000) === 'مليونا ريال', w(2000000));
ok('وثلاثة ملايين وخمسمائة ألف', w(3500000) === 'ثلاثة ملايين وخمسمائة ألف ريال', w(3500000));

/* الهللات */
ok('الكسر يُقال هللات', w(2500000.5) === 'مليونان وخمسمائة ألف ريال وخمسون هللةً', w(2500000.5));
ok('وما دون الريال يُقال وحده بلا «ريال» معلَّقة', w(0.5) === 'خمسون هللةً', w(0.5));
ok('والهللةُ الواحدة', w(0.01) === 'هللة واحدة', w(0.01));
ok('والهللتان', w(0.02) === 'هللتان', w(0.02));

/* الحدود */
ok('الصفر يُقال', w(0) === 'صفر ريال', w(0));
ok('والسالب لا يُفقَّط', w(-5) === '');
// `Number(null)` و`Number('')` و`Number([])` أصفارٌ في جافاسكربت — ومبلغٌ غائبٌ يُطبع
// «صفر ريال» في سندِ قبضٍ أسوأُ من فراغ. فالصفرُ الصريحُ وحده يُقال صفرًا.
ok('وغيرُ الرقم لا يُفقَّط', ['كثير', null, undefined, '', '  ', [], {}, NaN, true]
  .every((v) => w(v) === ''), JSON.stringify(['كثير', null, '', []].map(w)));
ok('والصفرُ الصريح يُقال', w(0) === 'صفر ريال' && w('0') === 'صفر ريال');
ok('وما بلغ المليار يُردّ رقمًا لا نصًّا خاطئًا', w(1000000000).includes('1,000,000,000'), w(1000000000));
ok('ولا فراغَ في أوّل نصٍّ ولا آخره', [1, 2, 3, 100, 1000, 25500, 0.5].every((n) => w(n) === w(n).trim()));
ok('ولا «undefined» ولا «NaN» في أيّ مبلغ',
  [1, 2, 3, 11, 99, 100, 101, 200, 999, 1000, 2000, 11000, 999999, 1000001, 123456789]
    .every((n) => !/undefined|NaN/.test(w(n))));
